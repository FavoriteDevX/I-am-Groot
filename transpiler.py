#!/usr/bin/env python3
"""
GrootLang Transpiler
Converts any text message into an executable .groot program.
Usage: python transpiler.py "Your secret message" > secret.groot
"""

import sys

def generate_number_instructions(n):
    """Generates optimal GrootLang instructions to push integer n onto the stack."""
    if n == 0:
        return ["i am groot."]
    
    instructions = []
    hundreds = n // 100
    remainder = n % 100
    tens = remainder // 10
    ones = remainder % 10

    first = True

    for _ in range(hundreds):
        instructions.append("I AM GROOT!")
        if not first:
            instructions.append("I am Groot+")
        first = False

    for _ in range(tens):
        instructions.append("I am Groot!")
        if not first:
            instructions.append("I am Groot+")
        first = False

    for _ in range(ones):
        instructions.append("I am Groot.")
        if not first:
            instructions.append("I am Groot+")
        first = False

    return instructions

def text_to_groot(text):
    output = ["// Auto-generated by GrootLang Transpiler", ""]
    for char in text:
        ascii_val = ord(char)
        output.append(f"// Character: {repr(char)} (ASCII {ascii_val})")
        output.extend(generate_number_instructions(ascii_val))
        output.append("I AM GROOT.")
        output.append("")
    output.append("WE ARE GROOT!")
    return "\n".join(output)

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print('Usage: python transpiler.py "Hello World!" > output.groot', file=sys.stderr)
        sys.exit(1)
    
    message = " ".join(sys.argv[1:])
    print(text_to_groot(message))
